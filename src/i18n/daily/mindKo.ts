export function mindCards(t: TodayData): MindCard[] {
  const g = (GROUP_OF as Record<string, Group>)[t.luck.stemSipsin] as string
  const gp = (GROUP_PLAIN as Record<string, string>)[g] ?? ''
  const w = (WEATHER[g] ?? WEATHER['비겁'])[tierOf(t.score)]
  const wl = (WALLET[g] ?? WALLET['비겁'])[tierOf(t.axes.money)]
  const y = t.who.yongEl as Element
  const RANK: Record<string, number> = { 용신: 2, 희신: 1, 한신: 0, 구신: -1, 기신: -2 }
  const sr = RANK[t.luck.stemRole] ?? 0, br = RANK[t.luck.branchRole] ?? 0
  const helpSip = sr >= br ? t.luck.stemSipsin : t.luck.branchSipsin
  const helped = Math.max(sr, br) > 0
  const hg = (GROUP_OF as Record<string, Group>)[helpSip] as string
  const c = helped ? (CHEM_G[hg] ?? CHEM.earth) : (CHEM[y] ?? CHEM.earth)
  const hap = ANIMAL[HAP_OF[BH.indexOf(t.dayGanzi[1])]]
  return [
    { id: 'weather', emoji: '🌤️', art: 'mind-weather', title: '오늘의 마음 날씨', ask: '오늘 내 마음에는 어떤 날씨가 들까?', name: w[0], text: w[1], tip: w[2], why: `오늘 하늘 기운이 나에게 ${t.luck.stemSipsin}(${gp})이고, 총운이 ${t.score}점이라서 이렇게 나왔어요.` },
    { id: 'chem', emoji: '🤝', art: 'mind-chem', title: '오늘 나와 케미 좋은 사람', ask: '오늘 누구를 만나면 좋을까?', name: c[0], text: `${c[1]} 띠로는 ${hap}띠와 잘 통하고, 만나기 좋은 때는 ${SLOT_KO[t.bestSlot]}이에요.`, tip: c[2], why: `${helped ? `오늘 일진의 ${helpSip}(${(GROUP_PLAIN as Record<string, string>)[hg] ?? ''}) 기운이 나를 도와서 그 기운을 닮은 사람이 잘 맞아요.` : `오늘 일진은 나에게 부담이 되는 기운이에요. 내 사주에 가장 필요한 기운이 ${EL_KO[y] ?? ''} 그 기운을 닮은 사람이 힘이 돼요.`} ${hap}띠는 오늘 일진과 육합이에요.` },
    { id: 'wallet', emoji: '👛', art: 'mind-wallet', title: '오늘의 지갑 경보', ask: '오늘 내 지갑은 안전할까?', name: wl[0], text: wl[1], tip: wl[2], why: `오늘 하늘 기운이 나에게 ${t.luck.stemSipsin}(${gp})이고, 재물운이 ${t.axes.money}점이라서 이렇게 나왔어요.` },
  ]
}
