/* ───────── 도우미 ───────── */
function detectFeelings(text: string, chips: string[]): string[] {
  const out = new Set(chips)
  for (const [f, ks] of FEEL_KEYS) if (has(text, ks)) out.add(f)
  return [...out].slice(0, 5)
}
function rank(text: string, scene: string): Array<Sym & { tone?: Tone }> {
  const scored = SYMBOLS.map((s) => {
    let sc = 0
    for (const k of s.keys) {
      if (!keyHit(text, k)) continue
      sc += 1
      if (keyHit(scene, k)) sc += 3
    }
    return { s, sc }
  }).filter((x) => x.sc > 0)
  scored.sort((a, b) => b.sc - a.sc)
  return scored.slice(0, 6).map((x) => x.s as Sym & { tone?: Tone })
}

