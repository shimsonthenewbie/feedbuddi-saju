let fail = 0
for (const c of C) {
  const r = readDreamFree({ dream: c.d, feelings: [] })
  const names = r.symbols.map((s) => s.name)
  const why: string[] = []
  if (c.title && r.headline !== c.title) why.push(`제목 ${r.headline} (기대 ${c.title})`)
  if (c.tone && r.tone !== c.tone) why.push(`톤 ${r.tone} (기대 ${c.tone})`)
  for (const n of c.sym ?? []) if (!names.some((x) => x.includes(n))) why.push(`상징 없음: ${n}`)
  for (const n of c.no ?? []) if (names.some((x) => x === n || x.includes(n))) why.push(`나오면 안 되는 상징: ${n} (${names.join(',')})`)
  for (const n of c.noTitle ?? []) if (r.headline === n || r.story.join(' ').includes(n)) why.push(`나오면 안 되는 풀이: ${n}`)
  if (why.length) { fail++; console.log(`✗ ${c.d.slice(0, 40)}\n    ${why.join('\n    ')}`) }
}
console.log(`\n꿈 검사 ${C.length - fail}/${C.length} 통과`)
process.exit(fail ? 1 : 0)
